String sourceADescription() {
    if (!gridImportDevice && !solarExportDevice) return "Not configured (optional)"
    if (!gridImportDevice || !solarExportDevice) return "⚠️ Partially configured — both devices required"
    return "From grid: ${gridImportDevice.displayName}\nTo grid:   ${solarExportDevice.displayName}"
}

String sourceBDescription() {
    if (!gridKwhDevice && !solarKwhDevice) return "Not configured (optional)"
    if (!gridKwhDevice || !solarKwhDevice) return "⚠️ Partially configured — both devices required"
    return "Grid: ${gridKwhDevice.displayName}\nSolar: ${solarKwhDevice.displayName}" +
           (peakWattsDevice ? "\nPeak meter: ${peakWattsDevice.displayName}" : "")
}

String ratesDescription() {
    return "Net: ${currentNetRate}¢ | Import: ${proposedImportRate}¢ | " +
           "Export: ${proposedExportRate}¢ | Demand: \$${demandChargeRate}/kW"
}

String notifyDescription() {
    if (!notifyDevices) return "No notifications configured"
    return "${notifyDevices.size()} device(s) | Spike: ${spikeThresholdKw ?: 'off'} kW | " +
           "Discrepancy: ${discrepancyThresholdPct ?: 5}%"
}

