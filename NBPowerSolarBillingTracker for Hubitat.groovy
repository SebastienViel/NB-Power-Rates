double safeWatts(dev) {
    try {
        def v = dev?.currentValue("power")
        return (v != null) ? (v as double) : 0.0
    } catch (e) { logDebug "safeWatts error: ${e.message}"; return 0.0 }
}

double safeEnergy(dev) {
    try {
        def v = dev?.currentValue("energy")
        return (v != null) ? (v as double) : 0.0
    } catch (e) { logDebug "safeEnergy error: ${e.message}"; return 0.0 }
}

void sendNotifications(String msg) { notifyDevices?.each { it.deviceNotification(msg) } }

String formatDate(long ts) { return new Date(ts).format("yyyy-MM-dd HH:mm", location.timeZone) }

String currentBillingPeriodLabel() {
    def now = new Date()
    int day = now.date; int yr = now.year + 1900; int mo = now.month
    int bd  = (billingDay ?: 1) as int
    Date start
    if (day >= bd) {
        start = Date.parse("yyyy-M-d", "${yr}-${mo + 1}-${bd}")
    } else {
        def cal = Calendar.getInstance(); cal.set(yr, mo - 1, bd); start = cal.time
    }
    return start.format("MMM d") + " – " + (start + 30).format("MMM d, yyyy")
}

