/**
 *  NB Power Solar Billing Tracker  v1.5
 *
 *  Monitors energy data to compare the current NB Power net metering rate
 *  structure against the proposed three-part rate (import rate + export credit
 *  + demand charge), pending EUB approval April 1, 2027.
 *
 *  Both meter sources run simultaneously and independently:
 *
 *  SOURCE A — PowerMeter (watts), e.g. Emporia Vue via amithalp/EmporiaV2
 *    - Two devices: "mains from grid" and "mains to grid", both PowerMeter
 *    - App polls watts every minute and integrates to kWh internally
 *    - Feeds the 15-min rolling average for peak demand tracking
 *    - Optional — leave devices unset to disable Source A
 *
 *  SOURCE B — EnergyMeter (kWh, never-resetting), e.g. Aeotec
 *    - Grid consumption: total kWh drawn from NB Power (never resets)
 *    - Solar production: total kWh generated by inverter (never resets)
 *    - App snapshots both counters at billing period start, computes delta
 *    - Peak demand uses an optional PowerMeter, or estimates from kWh delta
 *    - Optional — leave devices unset to disable Source B
 *
 *  When both sources are active the app:
 *    - Calculates billing costs independently for each source
 *    - Compares import kWh, export kWh, and both cost models between sources
 *    - Flags discrepancies above a configurable threshold
 *    - Reports both sets of figures in the status paragraph and dashboard
 *    - Uses Source A peak demand for both billing calculations when available
 *      (watts integration is more accurate than kWh-delta estimation)
 *
 *  Billing formulas (applied to each source independently):
 *    Current net metering : (importKwh − exportKwh) × currentRate
 *    Proposed structure   : (importKwh × importRate)
 *                         − (exportKwh × exportRate)
 *                         + (peakKw    × demandCharge)
