    double peak  = peakKw()
    boolean hasA = sourceAActive()
    boolean hasB = sourceBActive()

    double aImp  = aImportKwh().round(2)
    double aExp  = aExportKwh().round(2)
    double bImp  = bImportKwh().round(2)
    double bExp  = bExportKwh().round(2)

    Map aC = hasA ? calcCosts(aImp, aExp, peak) : null
    Map bC = hasB ? calcCosts(bImp, bExp, peak) : null

    def sb = new StringBuilder()
    sb << "📊 NB Power Billing Period Summary\n"
    sb << "Period : ${state.billingStartStr} – ${formatDate(now())}\n"
    sb << "Peak 15-min demand: ${peak.round(3)} kW  (at ${state.peakKwTime ?: 'not recorded'})\n"
    sb << "─────────────────────────────────────\n"

    if (hasA) {
        sb << "SOURCE A (Emporia / watts)\n"
        sb << "  Grid import  : ${aImp} kWh\n"
        sb << "  Solar export : ${aExp} kWh\n"
        sb << "  Net kWh      : ${(aImp - aExp).round(2)} kWh\n"
        sb << "  Current net metering  : \$${aC.currentCost}\n"
        sb << "  Proposed structure    : \$${aC.proposedCost}\n"
        sb << "    Import  ${aImp} kWh × ${proposedImportRate}¢  =  \$${aC.importCost}\n"
        sb << "    Export  ${aExp} kWh × ${proposedExportRate}¢  = −\$${aC.exportCredit}\n"
        sb << "    Demand  ${peak.round(3)} kW × \$${demandChargeRate}  =  \$${aC.demandCost}\n"
        sb << "  Proposed vs. current  : ${aC.delta >= 0 ? '+' : ''}\$${aC.delta}\n"
        sb << "  Annualised projection : ${aC.delta >= 0 ? '+' : ''}\$${(aC.delta * 12).round(0)}/yr\n"
        sb << "─────────────────────────────────────\n"
    }

    if (hasB) {
        sb << "SOURCE B (Aeotec / kWh)\n"
        sb << "  Grid import       : ${bImp} kWh\n"
        sb << "  Solar production  : ${bExp} kWh\n"
        sb << "  Net kWh           : ${(bImp - bExp).round(2)} kWh\n"
        sb << "  Current net metering  : \$${bC.currentCost}\n"
        sb << "  Proposed structure    : \$${bC.proposedCost}\n"
        sb << "    Import  ${bImp} kWh × ${proposedImportRate}¢  =  \$${bC.importCost}\n"
        sb << "    Export  ${bExp} kWh × ${proposedExportRate}¢  = −\$${bC.exportCredit}\n"
        sb << "    Demand  ${peak.round(3)} kW × \$${demandChargeRate}  =  \$${bC.demandCost}\n"
        sb << "  Proposed vs. current  : ${bC.delta >= 0 ? '+' : ''}\$${bC.delta}\n"
        sb << "  Annualised projection : ${bC.delta >= 0 ? '+' : ''}\$${(bC.delta * 12).round(0)}/yr\n"
        sb << "─────────────────────────────────────\n"
    }

    if (hasA && hasB) {
        double impDiffPct = (Math.max(aImp, bImp) > 0) ?
            ((aImp - bImp).abs() / Math.max(aImp, bImp) * 100.0).round(1) : 0.0
        double expDiffPct = (Math.max(aExp, bExp) > 0) ?
            ((aExp - bExp).abs() / Math.max(aExp, bExp) * 100.0).round(1) : 0.0
        sb << "CROSS-SOURCE COMPARISON\n"
        sb << "  Import difference  : ${(aImp - bImp).round(2)} kWh (${impDiffPct}%)\n"
        sb << "  Export difference  : ${(aExp - bExp).round(2)} kWh (${expDiffPct}%)\n"
        sb << "  Cost delta (A−B)   : \$${(aC.proposedCost - bC.proposedCost).round(2)} proposed\n"
    }

    def msg = sb.toString()
    logInfo msg
    sendNotifications(msg)
}

