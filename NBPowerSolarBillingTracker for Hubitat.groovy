def initialize() {
    if (state.billingStart == null) resetBillingPeriod()
    schedule("0 * * * * ?", "everyMinute")
    schedule("0 0 0 ${billingDay} * ?", "autoBillingReset")

    def active = []
    if (sourceAActive()) active << "Source A (watts)"
    if (sourceBActive()) active << "Source B (kWh)"
    logInfo "Initialised. Active sources: ${active ?: ['none — configure devices']}. " +
            "Billing period: ${currentBillingPeriodLabel()}"
    refreshSummary()
}

