def resetBillingPeriod() {
    def ts = now()
    state.billingStart    = ts
    state.billingStartStr = formatDate(ts)

    // Source A — watt integration totals
    state.aImportKwh = 0.0
    state.aExportKwh = 0.0

    // Source B — never-resetting kWh baselines
    state.bImportBase = safeEnergy(gridKwhDevice)
    state.bExportBase = safeEnergy(solarKwhDevice)

    // Peak demand (shared — Source A watts is preferred source)
    state.minuteWatts      = []
    state.peakKw           = 0.0
    state.peakKwTime       = ""

    // Alert cooldowns
    state.lastSpikeAlert       = 0L
    state.lastDiscrepancyAlert = 0L

    logInfo "Billing period reset at ${state.billingStartStr}." +
            (sourceBActive() ? " Source B baselines — Grid: ${state.bImportBase} kWh, Solar: ${state.bExportBase} kWh." : "")
}

// ---------------------------------------------------------------------------
// Every-minute handler
// ---------------------------------------------------------------------------
def everyMinute() {
    // ── Source A: integrate watts to kWh ────────────────────────────────
    double importW = 0.0
    if (sourceAActive()) {
        importW              = Math.max(0.0, safeWatts(gridImportDevice))
        double exportW       = Math.max(0.0, safeWatts(solarExportDevice))
        state.aImportKwh     = (state.aImportKwh ?: 0.0) + (importW / 1000.0 / 60.0)
        state.aExportKwh     = (state.aExportKwh ?: 0.0) + (exportW / 1000.0 / 60.0)
    }

    // ── Peak demand ──────────────────────────────────────────────────────
    // Priority: Source A import watts → dedicated peakWattsDevice → Source B kWh delta
    double wattsForDemand = 0.0
    if (sourceAActive()) {
        wattsForDemand = importW
    } else if (peakWattsDevice) {
        wattsForDemand = Math.max(0.0, safeWatts(peakWattsDevice))
    } else if (sourceBActive()) {
        // Estimate from Source B kWh delta
        double prev         = (state.prevBImportKwh ?: safeEnergy(gridKwhDevice)) as double
        double cur          = safeEnergy(gridKwhDevice)
        wattsForDemand      = Math.max(0.0, cur - prev) * 60.0 * 1000.0
        state.prevBImportKwh = cur
    }
    trackDemand(wattsForDemand)

    // ── Spike alert ──────────────────────────────────────────────────────
    checkSpikeAlert(wattsForDemand)

    // ── Discrepancy check ────────────────────────────────────────────────
    if (sourceAActive() && sourceBActive()) checkDiscrepancy()

    refreshSummary()
}

// ---------------------------------------------------------------------------
// Peak demand tracking (shared)
// ---------------------------------------------------------------------------
void trackDemand(double wattsNow) {
    int hr       = Calendar.getInstance(location.timeZone).get(Calendar.HOUR_OF_DAY)
    int winStart = (demandWindowStart ?: 7) as int
    int winEnd   = (demandWindowEnd   ?: 22) as int

    if (hr >= winStart && hr < winEnd) {
        List buf = state.minuteWatts ?: []
        buf << wattsNow
        if (buf.size() > 15) buf = buf.drop(buf.size() - 15)
        state.minuteWatts = buf

        if (buf.size() == 15) {
            double avgKw = (buf.sum() / 15.0) / 1000.0
            if (avgKw > (state.peakKw ?: 0.0)) {
                state.peakKw     = avgKw.round(4)
                state.peakKwTime = formatDate(now())
                logDebug "New peak 15-min demand: ${state.peakKw} kW at ${state.peakKwTime}"
            }
        }
    } else {
        state.minuteWatts = []
    }
}

// ---------------------------------------------------------------------------
// Spike alert
// ---------------------------------------------------------------------------
void checkSpikeAlert(double wattsNow) {
    double threshKw = (spikeThresholdKw ?: 0) as double
    if (threshKw <= 0) return
    if ((wattsNow / 1000.0) <= threshKw) return
    long cooldownMs = ((spikeAlertCooldownMin ?: 30) * 60 * 1000) as long
    if ((now() - (state.lastSpikeAlert ?: 0L)) > cooldownMs) {
        state.lastSpikeAlert = now()
        double kw     = (wattsNow / 1000.0).round(2)
        double impact = (kw * (demandChargeRate ?: 13.0)).round(2)
        sendNotifications(
            "⚡ Demand spike: grid draw is ${kw} kW (threshold ${threshKw} kW). " +
            "If sustained 15 min, demand charge impact: \$${impact}."
        )
    }
}

// ---------------------------------------------------------------------------
// Discrepancy check
// ---------------------------------------------------------------------------
void checkDiscrepancy() {
    double thresh = (discrepancyThresholdPct ?: 5.0) as double
    if (thresh <= 0) return

    double aImp = aImportKwh()
    double bImp = bImportKwh()
    double aExp = aExportKwh()
    double bExp = bExportKwh()

    // Only compare once each source has accumulated something meaningful (>1 kWh)
    if (aImp < 1.0 || bImp < 1.0) return

    double impDiffPct = Math.abs(aImp - bImp) / Math.max(aImp, bImp) * 100.0
    double expDiffPct = (Math.max(aExp, bExp) > 0.5) ?
                        Math.abs(aExp - bExp) / Math.max(aExp, bExp) * 100.0 : 0.0

    if (impDiffPct > thresh || expDiffPct > thresh) {
        long cooldownMs = ((discrepancyAlertCooldownMin ?: 60) * 60 * 1000) as long
        if ((now() - (state.lastDiscrepancyAlert ?: 0L)) > cooldownMs) {
            state.lastDiscrepancyAlert = now()
            def lines = []
            if (impDiffPct > thresh)
                lines << "Import: A=${aImp.round(2)} kWh vs B=${bImp.round(2)} kWh (${impDiffPct.round(1)}% difference)"
            if (expDiffPct > thresh)
                lines << "Export: A=${aExp.round(2)} kWh vs B=${bExp.round(2)} kWh (${expDiffPct.round(1)}% difference)"
            sendNotifications(
                "⚠️ Meter discrepancy detected:\n" + lines.join("\n") +
                "\nCheck your device configurations and wiring."
            )
        }
    }
}

// ---------------------------------------------------------------------------
// Per-source kWh calculations
// ---------------------------------------------------------------------------
double aImportKwh() { return (state.aImportKwh ?: 0.0) as double }
double aExportKwh() { return (state.aExportKwh ?: 0.0) as double }

double bImportKwh() {
    if (!sourceBActive()) return 0.0
    double cur  = safeEnergy(gridKwhDevice)
    double base = (state.bImportBase ?: 0.0) as double
    return Math.max(0.0, cur - base)
}

double bExportKwh() {
    if (!sourceBActive()) return 0.0
    double cur  = safeEnergy(solarKwhDevice)
    double base = (state.bExportBase ?: 0.0) as double
    return Math.max(0.0, cur - base)
}

double peakKw() { return (state.peakKw ?: 0.0) as double }

// ---------------------------------------------------------------------------
// Per-source billing calculations (peak is shared)
// ---------------------------------------------------------------------------
Map calcCosts(double imp, double exp, double peak) {
    double netKwh       = imp - exp
    double currentCost  = (netKwh   * ((currentNetRate    ?: 14.76) / 100.0)).round(2)
    double importCost   = (imp      * ((proposedImportRate ?: 14.76) / 100.0)).round(2)
    double exportCredit = (exp      * ((proposedExportRate ?: 6.77)  / 100.0)).round(2)
    double demandCost   = (peak     *  (demandChargeRate   ?: 13.00)).round(2)
    double proposedCost = (importCost - exportCredit + demandCost).round(2)
    double delta        = (proposedCost - currentCost).round(2)
    return [
        currentCost:  currentCost,
        importCost:   importCost,
        exportCredit: exportCredit,
        demandCost:   demandCost,
        proposedCost: proposedCost,
        delta:        delta
    ]
}

