def refreshSummary() {
    double peak  = peakKw()
    boolean hasA = sourceAActive()
    boolean hasB = sourceBActive()

    double aImp  = aImportKwh().round(2)
    double aExp  = aExportKwh().round(2)
    double bImp  = bImportKwh().round(2)
    double bExp  = bExportKwh().round(2)

    Map aC = hasA ? calcCosts(aImp, aExp, peak) : null
    Map bC = hasB ? calcCosts(bImp, bExp, peak) : null

    logDebug "=== Refresh ===" +
             (hasA ? " | A: imp=${aImp} exp=${aExp} cur=\$${aC.currentCost} prop=\$${aC.proposedCost}" : "") +
             (hasB ? " | B: imp=${bImp} exp=${bExp} cur=\$${bC.currentCost} prop=\$${bC.proposedCost}" : "") +
             " | Peak: ${peak} kW"

    if (summaryDevice) {
        if (hasA) {
            sendEvent(summaryDevice, [name: "nbpA_ImportKwh",    value: aImp,                                  unit: "kWh"])
            sendEvent(summaryDevice, [name: "nbpA_ExportKwh",    value: aExp,                                  unit: "kWh"])
            sendEvent(summaryDevice, [name: "nbpA_PeakKw",       value: peak.round(3),                         unit: "kW"])
            sendEvent(summaryDevice, [name: "nbpA_CurrentCost",  value: aC.currentCost,                        unit: "\$"])
            sendEvent(summaryDevice, [name: "nbpA_ProposedCost", value: aC.proposedCost,                       unit: "\$"])
            sendEvent(summaryDevice, [name: "nbpA_Delta",        value: "${aC.delta >= 0 ? '+' : ''}${aC.delta}", unit: "\$"])
        }
        if (hasB) {
            sendEvent(summaryDevice, [name: "nbpB_ImportKwh",    value: bImp,                                  unit: "kWh"])
            sendEvent(summaryDevice, [name: "nbpB_ExportKwh",    value: bExp,                                  unit: "kWh"])
            sendEvent(summaryDevice, [name: "nbpB_CurrentCost",  value: bC.currentCost,                        unit: "\$"])
            sendEvent(summaryDevice, [name: "nbpB_ProposedCost", value: bC.proposedCost,                       unit: "\$"])
            sendEvent(summaryDevice, [name: "nbpB_Delta",        value: "${bC.delta >= 0 ? '+' : ''}${bC.delta}", unit: "\$"])
        }
        sendEvent(summaryDevice, [name: "nbpPeakKw",       value: peak.round(3),           unit: "kW"])
        sendEvent(summaryDevice, [name: "nbpPeakKwTime",   value: state.peakKwTime ?: "—"])
        sendEvent(summaryDevice, [name: "nbpBillingStart", value: state.billingStartStr ?: "—"])

        // Discrepancy summary attribute
        if (hasA && hasB) {
            double impDiff = (aImp - bImp).abs().round(2)
            double expDiff = (aExp - bExp).abs().round(2)
            sendEvent(summaryDevice, [name: "nbpDiscrepancy",
                value: "Imp Δ: ${impDiff} kWh | Exp Δ: ${expDiff} kWh"])
        }
    }
}

