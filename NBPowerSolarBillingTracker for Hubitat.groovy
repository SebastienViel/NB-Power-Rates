String billingStatusParagraph() {
    double peak  = peakKw()
    boolean hasA = sourceAActive()
    boolean hasB = sourceBActive()

    if (!hasA && !hasB) return "<b>No sources configured.</b> Set up at least one source in the Meter Sources section above."

    double aImp  = aImportKwh().round(2)
    double aExp  = aExportKwh().round(2)
    double bImp  = bImportKwh().round(2)
    double bExp  = bExportKwh().round(2)
    Map aC = hasA ? calcCosts(aImp, aExp, peak) : null
    Map bC = hasB ? calcCosts(bImp, bExp, peak) : null

    def sb = new StringBuilder()
    sb << "<b>Period started:</b> ${state.billingStartStr ?: '(not set)'}<br>"
    sb << "<b>Peak 15-min demand:</b> ${peak.round(3)} kW (at ${state.peakKwTime ?: '—'})<br>"

    if (hasA) {
        String aSign = aC.delta >= 0 ? "+" : ""
        sb << "<br><b>── Source A (Emporia / watts) ──</b><br>"
        sb << "Import: <b>${aImp} kWh</b> &nbsp; Export: <b>${aExp} kWh</b><br>"
        sb << "Current net metering: <b>\$${aC.currentCost}</b><br>"
        sb << "Proposed structure:   <b>\$${aC.proposedCost}</b>"
        sb << " &nbsp; Δ <b>${aSign}\$${aC.delta}</b><br>"
    }

    if (hasB) {
        String bSign = bC.delta >= 0 ? "+" : ""
        sb << "<br><b>── Source B (Aeotec / kWh) ──</b><br>"
        sb << "Import: <b>${bImp} kWh</b> &nbsp; Solar production: <b>${bExp} kWh</b><br>"
        sb << "Current net metering: <b>\$${bC.currentCost}</b><br>"
        sb << "Proposed structure:   <b>\$${bC.proposedCost}</b>"
        sb << " &nbsp; Δ <b>${bSign}\$${bC.delta}</b><br>"
    }

    if (hasA && hasB) {
        double impDiff    = (aImp - bImp).round(2)
        double expDiff    = (aExp - bExp).round(2)
        double impDiffPct = (Math.max(aImp, bImp) > 0) ?
            ((aImp - bImp).abs() / Math.max(aImp, bImp) * 100.0).round(1) : 0.0
        double expDiffPct = (Math.max(aExp, bExp) > 0) ?
            ((aExp - bExp).abs() / Math.max(aExp, bExp) * 100.0).round(1) : 0.0
        double thresh     = (discrepancyThresholdPct ?: 5.0) as double

        String impFlag = impDiffPct > thresh ? " ⚠️" : " ✅"
        String expFlag = expDiffPct > thresh ? " ⚠️" : " ✅"

        sb << "<br><b>── Cross-source comparison ──</b><br>"
        sb << "Import diff: <b>${impDiff >= 0 ? '+' : ''}${impDiff} kWh (${impDiffPct}%)</b>${impFlag}<br>"
        sb << "Export diff: <b>${expDiff >= 0 ? '+' : ''}${expDiff} kWh (${expDiffPct}%)</b>${expFlag}<br>"
        sb << "Proposed cost diff (A−B): <b>\$${(aC.proposedCost - bC.proposedCost).round(2)}</b>"
    }

    return sb.toString()
}

